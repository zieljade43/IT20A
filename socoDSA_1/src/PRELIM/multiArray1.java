
package PRELIM;


public class multiArray1 {
    public static void main(String args[]) {
         int marks[][]={
             
             {22,30,37,25},
             {38,47,29,25},
             {26,27,20,19},
     
         };
     for (int i = 0;i<marks.length;i++) {
         for (int j = 0; j<marks[i].length; j++) {
         System.out.print(marks[i][j]+" ");
         }
         System.out.println();
     }
    }
}
    
    

